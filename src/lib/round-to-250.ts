/**
 * تقريب المبلغ لأقرب مضاعف لـ 250 دينار عراقي
 * أمثلة:
 *   103400 → 103500 (400 أقرب لـ 500)
 *   103250 → 103250 (بالضبط)
 *   103124 → 103000 (124 أقرب لـ 0)
 *   103625 → 103750 (625 أقرب لـ 750)
 */
export function roundTo250(amount: number): number {
  return Math.round(amount / 250) * 250
}
